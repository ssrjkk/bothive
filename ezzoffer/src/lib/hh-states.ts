/**
 * Состояния переписки на hh.ru и их перевод во внутренний статус.
 *
 * Отдельный модуль, а не условия внутри цикла синхронизации, потому что
 * соответствие состояний платформы и наших статусов — это факт о площадке,
 * а не логика приложения. Он должен читаться и проверяться сам по себе.
 *
 * ## Откуда список состояний
 *
 * Живой словарь `GET https://api.hh.ru/dictionaries`, ключ `negotiations_state`.
 * Проверен против ответа площадки, а не взят из документации по памяти:
 *
 *   response     Отклик
 *   invitation   Приглашение
 *   discard      Отказ
 *   hidden       Скрытый
 *   interview    Собеседование
 *   hired        Выход на работу
 *
 * ## Что было сломано
 *
 * Модуль утверждал, что соответствие «взято из документации hh.ru», и
 * содержал состояния, которых у соискателя на hh НЕТ: `viewed`, `chat`,
 * `chat_message`, `screening`, `invited`, `offer`, `rejected`,
 * `rejected_after_review`, `declined`, `discarded`, `cancelled`, `invalid`,
 * `not_relevant`, `apply`, `init`, `in_progress`, `on_hold`, `success`.
 *
 * Из реального словаря в таблице не было НИ ОДНОГО, кроме `invitation`.
 * Последствия были не косметические:
 *
 *  - `discard` («Отказ») не попадал ни в таблицу, ни в CLOSED_STATES, поэтому
 *    ветка записи `status='declined'` была недостижима, и «Отказы» в
 *    статистике равнялись нулю ВСЕГДА. Ровно тот симптом, который модуль был
 *    написан ради устранения.
 *  - `interview` и `hired` — сильнейшие исходы — попадали в «нет ответа».
 *  - VIEWED_STATES состоял из несуществующих id, поэтому `isViewedState()`
 *    был почти всегда false и `viewed_at` не записывался никогда.
 *
 * ## Просмотры: почему их нет в состоянии
 *
 * У hh нет состояния «резюме посмотрели». Состояния перечислены выше, и
 * «просмотра» среди них нет — площадка не отдаёт соискателю факт открытия
 * резюме вообще. Единственный честный признак, что работодатель дошёл до
 * рассмотрения, — флаг `reviewed` в самой переписке; он означает «отклик
 * рассмотрен», а не «страницу открыли и закрыли».
 *
 * Поэтому `reviewedAt` здесь означает именно «рассмотрено работодателем», и
 * нигде не называется «просмотрено резюме»: подмена одного другим дала бы в
 * статистике цифру, которой нет.
 */

export type AppResponse =
  /** Отправлен, реакции нет. */
  | ''
  /** HR посмотрел резюме, но не ответил. */
  | 'viewed'
  /** HR задал вопрос — нужно ответить. */
  | 'question'
  /** Приглашение на собеседование. */
  | 'interview'
  /** Вакансия закрыта, отказ. */
  | 'decline'
  /** Соискатель отказался сам. */
  | 'withdrawn';

/**
 * Состояния hh → наш статус.
 *
 * Отдельное оговорение по `hidden`: площадка прячет переписку по
 * настройкам видимости и по причинам, которые соискателю не показывает
 * («Не отправлять отклики», «Не показывать вакансии»). Это НЕ отказ
 * работодателя и НЕ отсутствие ответа. Приравнивать его к отказу было бы
 * прямой ложью в статистике, поэтому он остаётся «нет ответа» и попадает в
 * причину отказа при закрытом сценарии, а не в сам отказ.
 */
const STATE_TO_RESPONSE: Record<string, AppResponse> = {
  // Свежий отклик, реакции нет.
  response: '',

  // Приглашение и дальше по воронке.
  invitation: 'interview',
  interview: 'interview',

  // Единственный настоящий «отказ» на стороне соискателя.
  discard: 'decline',

  // Работодатель взял на работу: исход сильнее отказа, но модель статуса
  // оффера не имеет. Состояние попадает в response_note.
  hired: 'interview',

  // Скрыт самим соискателем или площадкой — не сигнал от работодателя.
  hidden: '',
};

/**
 * Состояния, при которых отклик окончательно закрыт.
 *
 * Только `discard`: он единственный означает «работодатель отказал».
 * `hidden` сюда НЕ входит намеренно — это действие соискателя.
 */
const CLOSED_STATES = new Set(['discard']);

/**
 * Наш статус для состояния hh. Неизвестные состояния — «нет ответа».
 *
 * Возврат "" для неизвестного состояния осознан: площадка добавляет состояния
 * и раньше добавляла. Придумывать для них отказ значило бы писать в
 * статистику выдумку.
 */
export function responseForHhState(state: string | null | undefined): AppResponse {
  if (!state) return '';
  return STATE_TO_RESPONSE[state] ?? '';
}

/**
 * Закрыт ли отклик окончательно.
 *
 * Функция снята: у VIEWED_STATES не осталось ни одного реального
 * состояния площадки, а сам факт рассмотрения приходит отдельным флагом
 * `reviewed` из тела переписки, а не из состояния. Синхронизация читает его
 * напрямую — так нельзя случайно решить, что «просмотренных откликов нет»,
 * потому что набор состояний случайно оказался неполным. Именно этим
 * был предыдущий баг.
 */
export function isClosedState(state: string | null | undefined): boolean {
  if (!state) return false;
  return CLOSED_STATES.has(state);
}

/**
 * Рассмотрел ли работодатель отклик.
 *
 * Вход — тело переписки, а не состояние. Единственный признак, который hh
 * реально отдаёт соискателю; называть его «просмотром резюме» нельзя.
 */
export function isReviewedNegotiation(reviewed: unknown): boolean {
  return reviewed === true;
}

/**
 * Человекочитаемое имя состояния.
 *
 * Нужно не для украшения: при отказе hh обычно пишет причину в `state.name`
 * («Отказ по причине отсутствия опыта», «Вакансия закрыта»), и именно она
 * объясняет пользователю, что именно не сработало. Раньше причина терялась:
 * сохранялось только слово `interview` или `question`.
 *
 * Теперь берётся ИМЯ ОТ САМОЙ ПЛОЩАДКИ, а не перевод ключа: `state.replace(
 * "_", " ")` на ключе `discarded` давал бы «discarded» — слово, которого
 * человек на русском не знает, то есть вместо объяснения отказа — мусор.
 */
export function hhStateLabel(state: string | null | undefined): string | null {
  if (!state) return null;
  return state.replace(/_/g, ' ');
}

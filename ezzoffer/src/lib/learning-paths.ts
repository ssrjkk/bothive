/** План по навыку, если он описан. Для н��известных — null, а не выдумка. */
export function learningPath(skill: string): LearningPath | null {
  return PATHS[skill] ?? null;
}

/** Навыки, для которых есть готовый план. */
export function skillsWithPaths(): string[] {
  return Object.keys(PATHS).sort((a, b) => a.localeCompare(b));
}

/** Группировка планов по категории — для порядка на странице. */
export function pathsByCategory(): { category: SkillCategory; paths: LearningPath[] }[] {
  const order: SkillCategory[] = ['lang', 'framework', 'data', 'devops', 'other'];
  const grouped = new Map<SkillCategory, LearningPath[]>();
  for (const path of Object.values(PATHS)) {
    const list = grouped.get(path.skill === '' ? 'other' : categoryOf(path.skill));
    if (list) list.push(path);
    else grouped.set(categoryOf(path.skill), [path]);
  }
  return order.filter((c) => grouped.has(c)).map((c) => ({ category: c, paths: grouped.get(c)! }));
}

function categoryOf(skill: string): SkillCategory {
  // Словарь навыков — единственный источник правды о категории; здесь только
  // подстраховка на случай, если навыка в нём нет.
  return skillCategory(skill) ?? 'other';
}

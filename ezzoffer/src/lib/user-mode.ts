/**
 * Режим пользователя: demo — без реальных откликов, live — с ними.
 *
 * Колонка `users.mode` введена с правилом «живой режим только по явному
 * согласию»: дефолт `demo`, переключение в `live` — только через `/api/mode`
 * и только при подключённом hh. Отключение hh гасит live обратно в demo
 * (`clearHhConnection`).
 *
 * ЧТО БЫЛО СЛОМАНО. Правило существовало только на словах. `mode` читался
 * ровно в трёх местах: сам роут `/api/mode`, баннер в кабинете и текстовая
 * приписка в боте (`withModeNotice`). Ни один путь отправки отклика его не
 * смотрел — ни плановый прогон, ни `/отклик` из бота, ни кнопка
 * «Откликнуться» в кабинете.
 *
 * Итог был хуже отсутствия переключателя: человек читал в интерфейсе
 * «Демо-режим», нажимал «Откликнуться» и отклик уходил от его имени на hh.
 * Переключатель менял надписи, а не поведение, то есть вводил в заблуждение
 * сильнее, чем его отсутствие.
 *
 * Теперь проверка одна и общая для всех трёх путей, и она живёт здесь, а не
 * в коде каждого из них: дублировать такое правило в трёх местах — значит
 * через месяц получить три разных ответа на вопрос «можно ли отправлять».
 */

import type { User } from './db';

export type UserMode = 'demo' | 'live';

/** Живёт ли аккаунт по-настоящему. Единственное место, где это решается. */
export function isLiveMode(user: Pick<User, 'mode'> | null | undefined): boolean {
  return user?.mode === 'live';
}

/**
 * Что человек видит вместо отправки.
 *
 * Один текст на три пути: планировщик, бот и кабинет. Разные формулировки
 * означали бы, что продукт сам не знает, что предлагает человеку сделать.
 */
export const DEMO_MODE_MESSAGE =
  'Вы в демо-режиме — реальные отклики не отправляются. ' +
  'Включите живой режим в разделе «Настройки», когда будете готовы откликаться от своего имени.';

/**
 * Короткая причина для чата.
 *
 * Отдельная строка, а не сокращение DEMO_MODE_MESSAGE: в Telegram читают
 * одну-две строки, и длинный текст в ответе на команду выглядит как
 * простыня. Формулировка отрицательная («не отправляются»), поэтому и
 * проверка «обещает ли команда действия» в `tests/telegram-commands.test.ts`
 * её не принимает за обещание отправить.
 */
export const DEMO_MODE_BRIEF =
  'Демо-режим: реальные отклики не уходят. Включите живой режим в «Настройках».';

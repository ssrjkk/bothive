import test from 'node:test';
import assert from 'node:assert/strict';

import { parseParamId } from '../src/lib/validate';

/**
 * Разбор идентификатора из адреса.
 *
 * Таблица входов, а не пример. Помощник разбирал значение через Number и
 * проверял «целое и больше нуля», а Number умеет то, чего не умеет обычный
 * идентификатор: «1e3» — это 1000, «0x10» — это 16, « 1 » — это 1, «1.0» —
 * это 1. Все четыре проходили проверку, и `/api/applications/1e3` вёл к
 * отклику № 1000 вместо отказа.
 *
 * Числа за пределом безопасного целого тоже проходили: Number округляет их, и
 * после округления это уже не тот идентификатор, который прислал клиент.
 *
 * Таблица зафиксирована целиком, чтобы регрессия ломала сборку сразу, а не
 * после того, как кто-то снова упростит проверку до Number.
 */

const ACCEPTED: [string, number][] = [
  ['1', 1],
  ['42', 42],
  ['1000', 1000],
  ['9007199254740991', Number.MAX_SAFE_INTEGER],
  ['123456789', 123456789],
];

const REJECTED: [string, string][] = [
  ['', 'пустая строка'],
  [' ', 'пробел — Number даёт 0'],
  ['   1   ', 'пробелы вокруг числа'],
  ['0', 'ноль не идентификатор'],
  ['-1', 'отрицательное'],
  ['1e3', 'экспоненциальная запись даёт 1000'],
  ['0x10', 'шестнадцатеричная запись даёт 16'],
  ['1.0', 'дробная запись даёт целое'],
  ['1.5', 'нецелое'],
  ['abc', 'не число'],
  ['1abc', 'хвост после числа'],
  ['+1', 'явный плюс'],
  ['9007199254740993', 'за пределом безопасного целого, Number округлит'],
  ['Infinity', 'бесконечность проходит isFinite'],
  ['1\n', 'перевод строки'],
];

test('идентификатор принимается только в обычной десятичной записи', () => {
  for (const [input, want] of ACCEPTED) {
    assert.equal(parseParamId(input), want, `«${input}» должен разбираться как ${want}`);
  }
});

test('идентификатор отклоняется во всех остальных формах', () => {
  for (const [input, why] of REJECTED) {
    assert.equal(parseParamId(input), null, `«${input}» не должен проходить: ${why}`);
  }
});

test('отсутствующий или нестроковый параметр не превращается в число', () => {
  assert.equal(parseParamId(undefined), null);
  assert.equal(parseParamId(null as unknown as string), null);
  assert.equal(parseParamId(42 as unknown as string), null);
});

/**
 * Поведение, а не форма.
 *
 * Число, которое Number и isInteger считали целым, на самом деле им не было:
 * «1e3» — это 1000, и такой адрес вёл к чужому ресурсу вместо отказа.
 */
test('экспоненциальная запись не ведёт к чужому идентификатору', () => {
  const parsed = parseParamId('1e3');
  assert.equal(parsed, null, 'разбор «1e3» дал отклик, которого не существует');
  assert.notEqual(Number('1e3'), null, 'Number разбирает это как 1000 — и в этом причина');
});

test('идентификатор не переполняется', () => {
  // Предыдущая строка ожидала Number.MAX_SAFE_INTEGER от 2^53 — это на единицу
  // больше предела, и Number.isSafeInteger правомерно его отклоняет.
  assert.equal(Number.MAX_SAFE_INTEGER, 9007199254740991);
  assert.equal(parseParamId('9007199254740991'), 9007199254740991, 'предел должен приниматься');
  assert.equal(parseParamId('9007199254740992'), null, '2^53 уже за пределом');
  assert.equal(parseParamId('9007199254740993'), null, 'и всё, что дальше');
});
